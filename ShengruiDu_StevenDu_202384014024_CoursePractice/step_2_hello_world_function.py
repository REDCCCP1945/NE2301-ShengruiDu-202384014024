"""Step 2 - print Hello World from inside a function."""


def say_hello() -> None:
    """Print the classic greeting."""
    print("Hello, World!")


def main() -> None:
    """Call the greeting function so it runs when the file is executed."""
    say_hello()


if __name__ == "__main__":
    main()
